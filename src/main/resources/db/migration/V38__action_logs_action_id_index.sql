-- Indexes the one foreign key in the schema whose child side has none, so deleting an action stops scanning the whole table.
--
-- `action_logs.action_id` REFERENCES actions(id) ON DELETE CASCADE. Postgres enforces that cascade with a query for the children of the row being
-- deleted, keyed on `action_id` alone - and no index here leads with that column. `action_logs_pkey` and `idx_action_logs_user_date` both lead with
-- `user_id`, which a lone `action_id` predicate cannot use, so every action delete fell back to a sequential scan of the entire table.
--
-- The cost is therefore proportional to the number of rows in `action_logs` ACROSS EVERY ACCOUNT, not to the logs of the action being removed - one
-- user deleting an action scanned every other user's history. Measured at 323,210 rows (a 30-action, 3-year account alongside 199 lighter ones):
--
--   * deleting an action with NO logs at all:  2.75 ms -> 0.30 ms
--   * deleting an action with 1,096 logs:      3.93 ms -> 1.67 ms
--   * the data import's clear-down (30):      21.4  ms -> 7.4  ms
--
-- The zero-log case is the one that proves it is a scan: without this index the cost is the same whether the action had a thousand log entries or
-- none, because the work is finding out that there are none.
--
-- This is NOT redundant with the (user_id, action_id, log_date) key. The application's own deletes (ActionLog.deleteByAction) do pass a user_id and
-- are served by it; the FK trigger is generated by Postgres and knows only the action, so it needs the column leading. It measured 2.3 MB at the
-- above size, ~7 bytes per row.
CREATE INDEX idx_action_logs_action_id ON action_logs (action_id);
